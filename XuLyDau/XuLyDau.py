    def tach_dau(self, word):
        word_no_tone = ""
        tone_name = "ngang"
        found_tone = False
        
        for char in word:
            if char in self.tone_map:
                base_char, t_name = self.tone_map[char]
                word_no_tone += base_char.lower()
                if not found_tone:
                    tone_name = t_name
                    found_tone = True
            else:
                word_no_tone += char.lower()
                
        return word_no_tone, tone_name